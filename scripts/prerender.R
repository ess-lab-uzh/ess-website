# Pre-render step: Quarto runs this automatically before every render,
# both on your computer and on GitHub (see `pre-render:` in _quarto.yml).
# Uses base R only, so there is nothing to install. It can also be run on
# its own from a terminal in the website folder:  Rscript scripts/prerender.R
#
# It does two things:
#
# 1. Projects. Reads every projects/<folder>/project.md and writes
#    projects/_projects.md: the grid of project cards and the pop-up window
#    for each project, shown on the Home and Research pages. Projects are
#    shown by `order:` (1 first); without `order:`, newest date first.
#    A project with `archive: true` is left out.
#    The image is shown on the card only; the pop-up shows title and text.
#    Header fields: title, date, order, person (not shown), image,
#    image-style (photo = fills the card, figure = shown whole on white),
#    image-position (focus point of a photo on the card, e.g. "50% 30%"),
#    image-credit (small text on the image), image-caption (shown when the
#    mouse rests on the card), archive.
#
# 2. Gallery. Reads gallery/gallery.csv and writes gallery/_photos.md,
#    the photo grid that gallery.qmd includes.
#
# Never edit projects/_projects.md or gallery/_photos.md by hand: they are
# rebuilt on every render. Edit the project.md files or gallery.csv instead.

# ---- helpers --------------------------------------------------------------

read_utf8 <- function(path) readLines(path, warn = FALSE, encoding = "UTF-8")

write_utf8 <- function(lines, path) {
  con <- file(path, open = "wb")
  writeLines(enc2utf8(lines), con, useBytes = TRUE)
  close(con)
}

html_escape <- function(x) {
  x <- gsub("&", "&amp;", x, fixed = TRUE)
  x <- gsub("<", "&lt;", x, fixed = TRUE)
  x <- gsub(">", "&gt;", x, fixed = TRUE)
  gsub('"', "&quot;", x, fixed = TRUE)
}

# Split a file into its header (simple `key: value` lines) and its text
read_project <- function(path) {
  lines  <- read_utf8(path)
  fences <- which(trimws(lines) == "---")
  if (length(fences) < 2 || fences[1] != 1) return(NULL)
  front <- lines[(fences[1] + 1):(fences[2] - 1)]
  body  <- if (fences[2] < length(lines)) lines[(fences[2] + 1):length(lines)] else character()
  meta  <- list()
  for (l in front) {
    m <- regmatches(l, regexec("^([A-Za-z0-9_-]+):\\s*(.*)$", l))[[1]]
    if (length(m) == 3) {
      v <- trimws(m[3])
      if (!grepl("^[\"']", v)) v <- trimws(sub("\\s+#.*$", "", v))  # drop a trailing # comment
      meta[[m[2]]] <- gsub("^['\"]|['\"]$", "", v)
    }
  }
  list(meta = meta, body = body)
}

# ---- 1. projects ----------------------------------------------------------

files <- sort(Sys.glob(file.path("projects", "*", "project.md")))
projects <- list()
for (f in files) {
  p <- read_project(f)
  if (is.null(p)) {
    message("prerender.R: warning: ", f, " has no header (--- ... ---); skipped")
    next
  }
  m <- p$meta
  if (identical(tolower(m[["archive"]]), "true")) next
  if (is.null(m[["title"]])) m[["title"]] <- basename(dirname(f))
  if (is.null(m[["date"]]))  m[["date"]]  <- substr(basename(dirname(f)), 1, 10)
  folder <- dirname(f)
  if (is.null(m[["image"]]) || !nzchar(m[["image"]])) {
    m[["image"]] <- ""
  } else if (!file.exists(file.path(folder, m[["image"]]))) {
    message("prerender.R: warning: ", f, ": image '", m[["image"]], "' not found")
    m[["image"]] <- ""
  }
  projects[[length(projects) + 1]] <- list(
    id = paste0("project-", gsub("[^A-Za-z0-9-]", "-", basename(folder))),
    folder = folder, meta = m, body = p$body)
}
ord   <- vapply(projects, function(p) if (is.null(p$meta[["order"]])) NA_real_ else as.numeric(p$meta[["order"]]), 0)
dates <- vapply(projects, function(p) p$meta[["date"]], "")
projects <- projects[order(is.na(ord), ord, -rank(dates, ties.method = "first"))]

field <- function(m, k) if (is.null(m[[k]])) "" else m[[k]]

md <- c("<!-- Generated by scripts/prerender.R from projects/*/project.md. Do not edit. -->",
        "", "```{=html}", '<div class="project-grid">')
for (p in projects) {
  m <- p$meta
  style  <- if (identical(field(m, "image-style"), "figure")) " is-figure" else ""
  pos    <- field(m, "image-position")
  credit <- html_escape(field(m, "image-credit"))
  img_html <- if (nzchar(m[["image"]])) {
    paste0('<img src="', p$folder, "/", m[["image"]], '" alt="" loading="lazy"',
           if (nzchar(pos)) paste0(' style="object-position:', html_escape(pos), '"') else "", ">",
           if (nzchar(credit)) paste0('<span class="img-credit">', credit, "</span>") else "")
  } else {
    '<span class="project-card-noimg" aria-hidden="true"><i class="bi bi-tree"></i></span>'
  }
  cap <- html_escape(field(m, "image-caption"))
  md <- c(md, paste0(
    '<a class="project-card" href="#', p$id, '" data-bs-toggle="modal" data-bs-target="#', p$id, '"',
    if (nzchar(cap)) paste0(' title="', cap, '"') else "", '>',
    '<span class="project-card-img', style, '">', img_html, '</span>',
    '<span class="project-card-title">', html_escape(m[["title"]]), '</span></a>'))
}
md <- c(md, "</div>", "```", "")

for (p in projects) {
  title <- html_escape(p$meta[["title"]])
  md <- c(md, "```{=html}", paste0(
    '<div class="modal fade project-modal" id="', p$id, '" tabindex="-1" aria-labelledby="', p$id, '-title" aria-hidden="true">',
    '<div class="modal-dialog modal-lg modal-dialog-centered modal-dialog-scrollable"><div class="modal-content">',
    '<button type="button" class="btn-close" data-bs-dismiss="modal" aria-label="Close"></button>',
    '<div class="modal-body"><div class="pm">',
    '<h2 id="', p$id, '-title">', title, "</h2>"),
    "```", "", p$body, "", "```{=html}",
    paste0('</div></div></div></div>',
           '<button type="button" class="project-nav project-prev" aria-label="Previous project">&#8249;</button>',
           '<button type="button" class="project-nav project-next" aria-label="Next project">&#8250;</button>',
           '</div>'),
    "```", "")
}
write_utf8(md, file.path("projects", "_projects.md"))
message("prerender.R: wrote projects/_projects.md (", length(projects), " project(s))")

# ---- 2. gallery -----------------------------------------------------------

gal_csv <- file.path("gallery", "gallery.csv")
if (file.exists(gal_csv)) {
  # Read as UTF-8 regardless of the computer's language settings
  g <- read.csv(text = read_utf8(gal_csv),
                stringsAsFactors = FALSE, na.strings = "", encoding = "UTF-8")
  g[is.na(g)] <- ""

  caption <- function(r) {
    place <- trimws(paste(r[["location"]], r[["year"]]))
    txt <- paste(c(r[["title"]], place)[nzchar(c(r[["title"]], place))],
                 collapse = ", ")
    if (nzchar(r[["photographer"]])) txt <- paste0(txt, " \u00a9 ", r[["photographer"]])
    txt
  }

  missing <- !file.exists(file.path("gallery", "photos", g$file))
  if (any(missing)) {
    message("prerender.R: warning: gallery.csv lists photos that are not in ",
            "gallery/photos/: ", paste(g$file[missing], collapse = ", "))
  }
  g <- g[!missing, , drop = FALSE]

  md <- c("<!-- Generated by scripts/prerender.R from gallery.csv. Do not edit. -->",
          "",
          "::: {.gallery-grid}", "")
  for (i in seq_len(nrow(g))) {
    cap <- gsub("([\\[\\]])", "\\\\\\1", caption(g[i, ]))
    md <- c(md,
            sprintf('![%s](gallery/photos/%s){group="gallery" loading="lazy" fig-alt="%s"}',
                    cap, g$file[i], gsub('"', "'", cap)),
            "")
  }
  md <- c(md, ":::")
  write_utf8(md, file.path("gallery", "_photos.md"))
  message("prerender.R: wrote gallery/_photos.md (", nrow(g), " photo(s))")
}
